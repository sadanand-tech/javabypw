package BasicsOfJava;

public class variableint {
    public static void main(String[] args) {
        int x;
        x=500;
        System.out.println(x);
        x=400;
        System.out.println(x);
        System.out.println(x+1);
        x = x + 5;
        System.out.println(x);
        x = x-10;
        System.out.println(x);
        int y= 5;
        System.out.println(y);
        y = 7;
        System.out.println(y);
        y=y-20;
        System.out.println(y);
        y= y-20;
        System.out.println(y);
    }
}
